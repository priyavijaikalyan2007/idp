#!/bin/bash

# ----------------------------------------------------------------------------
# ⚓ COMPONENT: clean.sh
# 📜 PURPOSE: Removes all build artifacts for a guaranteed clean rebuild.
#             Run from the repository root: ./clean.sh
# 🔗 RELATES: [[build.sh]], [[test.sh]]
# ----------------------------------------------------------------------------

set +e

SCRIPT_DIR=$( cd -- "$( dirname -- "${BASH_SOURCE[0]}" )" &> /dev/null && pwd )

echo "=== Cleaning compiled outputs ==="

# ----------------------------------------------------------------------------
# 1. Repo-root /target/ staging (populated by build.sh from the Maven module).
#    Dockerfile reads from /target/providers/ and /target/themes/.
# ----------------------------------------------------------------------------
if [ -d "${SCRIPT_DIR}/target" ]; then
    rm -rf "${SCRIPT_DIR}/target"
    echo "  Deleted target/"
fi

# ----------------------------------------------------------------------------
# 2. Maven's working dir inside the SPI module (classes/, test-classes/,
#    surefire-reports/, failsafe-reports/, jacoco/, the built JAR).
#    Equivalent to `mvn clean` but doesn't require Maven to run.
# ----------------------------------------------------------------------------
if [ -d "${SCRIPT_DIR}/src/providers/target" ]; then
    rm -rf "${SCRIPT_DIR}/src/providers/target"
    echo "  Deleted src/providers/target/"
fi

# ----------------------------------------------------------------------------
# 3. build.json (regenerated by build.sh on the next run).
# ----------------------------------------------------------------------------
if [ -f "${SCRIPT_DIR}/build.json" ]; then
    rm -f "${SCRIPT_DIR}/build.json"
    echo "  Deleted build.json"
fi

# ----------------------------------------------------------------------------
# 4. Editor + tooling scratch.
# ----------------------------------------------------------------------------
find "${SCRIPT_DIR}" -type d \( -name '.mvn' -o -name 'surefire-reports' -o -name 'failsafe-reports' \) \
    -not -path '*/node_modules/*' -prune -print0 2>/dev/null \
    | xargs -0 rm -rf 2>/dev/null

echo ""
echo "=== Clean complete ==="
echo "Rebuild with:   ./build.sh"
echo "Run tests with: ./test.sh"
